#!/usr/bin/env bash
# ===========================================================
# عالجمر — تشغيلُ كلِّ الحوارس في أمرٍ واحد
#
# لماذا هذا الملفّ: **سكربتُ فحصٍ موجودٌ في المستودعِ وغيرُ مربوطٍ بشيءٍ
# يُشغّله هو صفرُ تأكيدات.** في مشروعٍ سابقٍ بقي سكربتٌ بـ69 تأكيداً على
# مالِ الدرجِ لم يُشغَّل قطّ، وكان يُطمئنُ من يقرأ قائمةَ الملفّات.
# فكلُّ حارسٍ يُضاف هنا، وأيُّ حارسٍ في .kiro/tools/check_*.py غيرُ مذكورٍ
# في هذا الملفّ يُسقِط التشغيل.
#
# الاستخدام:  bash verify.sh
# ===========================================================
set -uo pipefail
cd "$(dirname "$0")"

pass=0
fail=0

run() {
  local label="$1"; shift
  printf '\n\033[1m── %s\033[0m\n' "$label"
  if "$@"; then
    pass=$((pass + 1))
  else
    fail=$((fail + 1))
    printf '\033[31m   ✗ سقط: %s\033[0m\n' "$label"
  fi
}

echo "═══════════ حوارسُ عالجمر ═══════════"

# الفحوصُ الذاتيّةُ أوّلاً: حارسٌ لم يُجرَّب على عطلٍ معروفٍ لا يُوثق به،
# وحارسٌ يسقط على نفسِه يُعطّل بعد حين.
run "فحوصُ حارسِ الأرقامِ الذاتيّة" \
    python3 .kiro/tools/check_numerals.py --selftest
run "فحوصُ حارسِ الوصلةِ الذاتيّة" \
    python3 .kiro/tools/check_wiring.py --selftest
run "فحوصُ حارسِ اللوحةِ الذاتيّة" \
    python3 .kiro/tools/check_palette.py --selftest

# وأدواتُ المعاينةِ والقياسِ لها فحوصُها أيضاً: أداةُ لقطةٍ معطوبةٌ
# تُخرج صورةً تبدو معقولةً لقسمٍ آخرَ (وقع هذا: ثمانُ لقطاتٍ كلُّها
# الواجهةُ قرأتُها سبعةَ أقسام)، وأداةُ قياسٍ معطوبةٌ تُبارك نصّاً
# غيرَ مقروء. وكلُّ هذه الفحوصِ لا تحتاج متصفّحاً.
run "فحوصُ أداةِ لقطةِ القسمِ الذاتيّة" \
    python3 .kiro/tools/section_shot.py --selftest
run "فحوصُ أداةِ القصِّ الذاتيّة" \
    python3 .kiro/tools/crop.py --selftest
run "فحوصُ أداةِ قياسِ السطوعِ الذاتيّة" \
    python3 .kiro/tools/measure_luma.py --selftest
run "فحوصُ أداةِ قياسِ جوفِ المحرفِ الذاتيّة" \
    python3 .kiro/tools/glyph_hollow.py --selftest
run "فحوصُ أداةِ خلوصِ الشعارِ الذاتيّة" \
    python3 .kiro/tools/mark_clear.py --selftest
run "فحوصُ أداةِ أشرطةِ الصفحةِ الذاتيّة" \
    python3 .kiro/tools/page_band.py --selftest

# ثمّ الحوارسُ على المشروع
run "لا أرقامَ بالرسمِ الهنديِّ أو الفارسيّ" \
    python3 .kiro/tools/check_numerals.py
run "كلُّ مرجعٍ يُصيب هدفاً موجوداً" \
    python3 .kiro/tools/check_wiring.py index.html
run "لا لونَ إلّا من لوحةِ المالك" \
    python3 .kiro/tools/check_palette.py

# **خلوصُ الشعارِ يُقاس في كلِّ دفعةٍ لا مرّةً واحدة.** كلمةُ «الجمر»
# تَستكنُّ في قوسِ العينِ بفارقٍ صغير، وأيُّ تعديلٍ في مقاسِ الكلمةِ
# أو ميلِها أو موضعِها يُلصِقها بالحبرِ فتصير لطخةً عند الطبعِ بلونٍ
# واحد. وحكَمتُ بالعينِ مرّتين فأخطأتُ المرّتين — والوضعُ (د) مقبولٌ
# في عينِي ومرفوضٌ في القياس، فهو مُستثنى هنا بقصد.
# **وتُفحَص كلُّ الأوضاعِ المعروضةِ لا ثلاثةٌ منها.** كان الفحصُ على
# (أ·ب·ج) وحدَها، ثمّ أُضيفت درجاتُ السُّمكِ وموديلا اللونِ — فكانت
# ستبقى **بلا فحصٍ** وهي التي تُعرَض على المالكِ الآن. وأيُّ وضعٍ
# يُعرَض ولا يُفحَص هو صفرُ تأكيدات.
run "كلمةُ الشعارِ لا تَلمس حبرَ العينِ وهي داخلَ القوس (كلُّ الأوضاع)" \
    python3 .kiro/tools/mark_clear.py docs/preview-harness/logo-ain.html \
      a b c e f g h i j k

# **تُفحَص الصورُ تنقيباً لا بنمطٍ مسطّح.** كان السطرُ
# `imgguard check docs/preview/*.png` فلم يرَ إلّا المجلّدَ الأوّل:
# أضفتُ 18 لقطةً في `docs/preview/v8/` ومرَّ الفحصُ أخضرَ **ولم يفحص
# واحدةً منها**. ومجلّدٌ جديدٌ يُنشأ في كلِّ دفعةٍ، فنمطٌ مسطّحٌ يعني
# أنّ أحدثَ الصورِ هي أقلُّها حراسةً — وهي التي تُقرأ فتُسقِط الجلسة.
# و`inbox/` مُستثنى بقصد: أصولُ المصوّرِ يجب أن تكون 6000×4000، وطلبتُها
# كذلك، فحارسٌ يُسقِط النشرَ لوصولِها يُعطَّل بعد حين. وقراءتُها يمنعها
# الخطّافُ عند القراءةِ لا هذا الفحص.
run "لا صورةَ تتجاوز 2000 بكسل (تنقيباً في docs وassets)" \
    bash -c 'find docs assets -type f \( -iname "*.png" -o -iname "*.jpg" \
      -o -iname "*.jpeg" -o -iname "*.webp" -o -iname "*.gif" \) -print0 \
      | xargs -0 --no-run-if-empty python3 .kiro/tools/imgguard.py check'

# محاسبةُ الحوارسِ نفسِها.
# **وتُحاسَب بسلوكِها لا باسمِها**: كان الفحصُ على `check_*.py` وحدَها،
# فأيُّ أداةٍ فيها `--selftest` باسمٍ آخرَ (section_shot · crop ·
# measure_luma) تبقى غيرَ مربوطةٍ = صفرُ تأكيدات، **وتسميةٌ مختلفةٌ
# تكفي للهربِ من المحاسبة**. فيُجمَع الاثنان: كلُّ `check_*.py`، وكلُّ
# ملفٍّ يُعلن `--selftest` أنّه يملك فحوصاً ذاتيّة.
printf '\n\033[1m── كلُّ حارسٍ وكلُّ أداةٍ ذاتِ فحوصٍ مربوطةٌ بهذا الملفّ\033[0m\n'
missing=0
targets="$(
  { ls .kiro/tools/check_*.py 2>/dev/null
    grep -l -- '--selftest' .kiro/tools/*.py 2>/dev/null
  } | sort -u
)"
for f in $targets; do
  [ -e "$f" ] || continue
  name="$(basename "$f")"
  # تُحذف أسطرُ التعليقِ أوّلاً: حارسٌ يقرأ شرحَه هو كأنّه كودٌ يُبارك العطل
  if grep -v '^[[:space:]]*#' "$0" | grep -q "$name"; then
    echo "  ✓ $name مربوط"
  else
    echo "  ✗ $name موجودٌ في المستودعِ وغيرُ مربوط = صفرُ تأكيدات"
    missing=$((missing + 1))
  fi
done
if [ "$missing" -eq 0 ]; then
  pass=$((pass + 1))
else
  fail=$((fail + 1))
fi

printf '\n═══════════════════════════════════\n'
printf 'نجح %d · سقط %d\n' "$pass" "$fail"
[ "$fail" -eq 0 ] || exit 1
printf '\033[32mكلُّ الحوارسِ خضراء.\033[0m\n'
